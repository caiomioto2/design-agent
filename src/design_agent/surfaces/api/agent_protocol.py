"""Agent Protocol v1 implementation for Design Agent.

Complies with the Agent Protocol specification (https://agentprotocol.ai).
Provides standardized task management, step execution, and binary artifact downloads.
"""

from __future__ import annotations

import hashlib
import mimetypes
import re
import time
import uuid
from pathlib import Path
from typing import Any, Literal

from fastapi import APIRouter, Depends, File, HTTPException, Query, Request, UploadFile
from fastapi.responses import FileResponse
from pydantic import BaseModel, Field

from design_agent.runtime.local import ApprovalPending, LocalRuntime, final_text

AP_STEPS = ("design_agent", "ap_steps")
THREAD_ID = re.compile(r"[A-Za-z0-9_.:-]{1,128}")
MAX_ATTACHMENTS = 10
MAX_ATTACHMENT_BYTES = 200 * 1024 * 1024


class Artifact(BaseModel):
    artifact_id: str = Field(description="Unique identifier for the artifact.")
    file_name: str = Field(description="Filename of the artifact.")
    relative_path: str | None = Field(default=None, description="Relative path within workspace.")
    created_at: str | None = Field(default=None, description="ISO timestamp of artifact creation.")


class TaskRequestBody(BaseModel):
    input: str | None = Field(default=None, description="Initial prompt for the task.")
    additional_input: dict[str, Any] | None = Field(
        default=None, description="Optional structured input payload."
    )


class Task(BaseModel):
    task_id: str = Field(description="Unique task identifier.")
    input: str | None = Field(default=None, description="Initial input prompt.")
    additional_input: dict[str, Any] | None = Field(default=None)
    artifacts: list[Artifact] = Field(
        default_factory=list, description="Artifacts generated by this task."
    )


class StepRequestBody(BaseModel):
    input: str | None = Field(default=None, description="Input for this execution step.")
    additional_input: dict[str, Any] | None = Field(
        default=None, description="Optional extra parameters for this step."
    )


class Step(BaseModel):
    task_id: str = Field(description="The task ID this step belongs to.")
    step_id: str = Field(description="Unique step identifier.")
    name: str | None = Field(default=None, description="Optional name of the step.")
    status: Literal["created", "running", "completed"] = Field(
        default="completed", description="Current step status."
    )
    output: str | None = Field(default=None, description="Text reply from the agent.")
    additional_output: dict[str, Any] | None = Field(default=None)
    artifacts: list[Artifact] = Field(
        default_factory=list, description="Artifacts produced by this step."
    )
    is_last: bool = Field(
        default=False, description="Whether this step completed the task execution."
    )


class Pagination(BaseModel):
    total_items: int
    total_pages: int
    current_page: int
    page_size: int


class TaskListResponse(BaseModel):
    tasks: list[Task]
    pagination: Pagination


class StepListResponse(BaseModel):
    steps: list[Step]
    pagination: Pagination


def _file_hash_id(file_name: str) -> str:
    return hashlib.sha256(file_name.encode("utf-8")).hexdigest()[:16]


def task_artifacts(runtime: LocalRuntime, task_id: str) -> list[Artifact]:
    folder = (runtime.out_dir / task_id).resolve()
    if not folder.is_dir():
        return []
    artifacts: list[Artifact] = []
    for p in sorted(folder.iterdir()):
        if p.is_file() and not p.name.startswith("."):
            try:
                stat = p.stat()
                created = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(stat.st_mtime))
            except OSError:
                created = None
            artifacts.append(
                Artifact(
                    artifact_id=_file_hash_id(p.name),
                    file_name=p.name,
                    relative_path=p.name,
                    created_at=created,
                )
            )
    return artifacts


def create_agent_protocol_router(
    caller_dep: Any,
    owned_validator: Any,
    threads_namespace: tuple[str, ...],
) -> APIRouter:
    router = APIRouter(prefix="/ap/v1/agent", tags=["Agent Protocol"])

    @router.post("/tasks", response_model=Task, status_code=200)
    async def create_task(
        body: TaskRequestBody,
        request: Request,
        caller: str = Depends(caller_dep),
    ) -> Task:
        task_id = f"task_{uuid.uuid4().hex[:16]}"
        state = request.app.state.api
        await state.store.aput(
            threads_namespace,
            task_id,
            {
                "owner": caller,
                "input": body.input,
                "additional_input": body.additional_input,
                "created_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            },
        )
        return Task(
            task_id=task_id,
            input=body.input,
            additional_input=body.additional_input,
            artifacts=[],
        )

    @router.get("/tasks", response_model=TaskListResponse)
    async def list_tasks(
        request: Request,
        page: int = Query(default=1, ge=1),
        page_size: int = Query(default=10, ge=1, le=100),
        caller: str = Depends(caller_dep),
    ) -> TaskListResponse:
        state = request.app.state.api
        items = await state.store.asearch(threads_namespace, limit=10_000)
        owned_items = [
            item
            for item in items
            if isinstance(item.value, dict) and item.value.get("owner") == caller
        ]
        total_items = len(owned_items)
        total_pages = max(1, (total_items + page_size - 1) // page_size)
        start = (page - 1) * page_size
        slice_items = owned_items[start : start + page_size]

        tasks = [
            Task(
                task_id=item.key,
                input=item.value.get("input") if isinstance(item.value, dict) else None,
                additional_input=item.value.get("additional_input")
                if isinstance(item.value, dict)
                else None,
                artifacts=task_artifacts(state.runtime, item.key),
            )
            for item in slice_items
        ]
        return TaskListResponse(
            tasks=tasks,
            pagination=Pagination(
                total_items=total_items,
                total_pages=total_pages,
                current_page=page,
                page_size=page_size,
            ),
        )

    @router.get("/tasks/{task_id}", response_model=Task)
    async def get_task(
        task_id: str,
        request: Request,
        caller: str = Depends(caller_dep),
    ) -> Task:
        await owned_validator(request, task_id, caller, create=False)
        state = request.app.state.api
        item = await state.store.aget(threads_namespace, task_id)
        data = item.value if (item and isinstance(item.value, dict)) else {}
        return Task(
            task_id=task_id,
            input=data.get("input"),
            additional_input=data.get("additional_input"),
            artifacts=task_artifacts(state.runtime, task_id),
        )

    @router.post("/tasks/{task_id}/steps", response_model=Step)
    async def execute_step(
        task_id: str,
        body: StepRequestBody,
        request: Request,
        caller: str = Depends(caller_dep),
    ) -> Step:
        await owned_validator(request, task_id, caller, create=False)
        state = request.app.state.api
        item = await state.store.aget(threads_namespace, task_id)
        task_data = item.value if (item and isinstance(item.value, dict)) else {}

        # Resolve step input (falling back to initial task input if step input is omitted)
        step_text = body.input
        if not step_text and not task_data.get("executed_initial"):
            step_text = task_data.get("input")

        if not step_text:
            raise HTTPException(status_code=400, detail="step input cannot be empty")

        try:
            added = await state.runtime.ask(step_text, thread_id=task_id)
        except ApprovalPending as error:
            raise HTTPException(status_code=409, detail=str(error)) from error

        # Mark initial input executed if applicable
        if not task_data.get("executed_initial"):
            task_data["executed_initial"] = True
            await state.store.aput(threads_namespace, task_id, task_data)

        output_text = final_text(added)
        artifacts = task_artifacts(state.runtime, task_id)
        is_last = not state.runtime.busy()

        step_id = f"step_{uuid.uuid4().hex[:12]}"
        step = Step(
            task_id=task_id,
            step_id=step_id,
            name="design_step",
            status="completed" if is_last else "running",
            output=output_text,
            additional_output=None,
            artifacts=artifacts,
            is_last=is_last,
        )

        # Record step in store
        steps = await state.store.asearch((*AP_STEPS, task_id), limit=10_000)
        await state.store.aput((*AP_STEPS, task_id), f"{len(steps):06d}", step.model_dump())

        return step

    @router.get("/tasks/{task_id}/steps", response_model=StepListResponse)
    async def list_steps(
        task_id: str,
        request: Request,
        page: int = Query(default=1, ge=1),
        page_size: int = Query(default=10, ge=1, le=100),
        caller: str = Depends(caller_dep),
    ) -> StepListResponse:
        await owned_validator(request, task_id, caller, create=False)
        state = request.app.state.api
        items = sorted(
            await state.store.asearch((*AP_STEPS, task_id), limit=10_000), key=lambda i: i.key
        )
        total_items = len(items)
        total_pages = max(1, (total_items + page_size - 1) // page_size)
        start = (page - 1) * page_size
        slice_items = items[start : start + page_size]
        steps = [Step(**item.value) for item in slice_items if isinstance(item.value, dict)]

        return StepListResponse(
            steps=steps,
            pagination=Pagination(
                total_items=total_items,
                total_pages=total_pages,
                current_page=page,
                page_size=page_size,
            ),
        )

    @router.get("/tasks/{task_id}/steps/{step_id}", response_model=Step)
    async def get_step(
        task_id: str,
        step_id: str,
        request: Request,
        caller: str = Depends(caller_dep),
    ) -> Step:
        await owned_validator(request, task_id, caller, create=False)
        state = request.app.state.api
        items = await state.store.asearch((*AP_STEPS, task_id), limit=10_000)
        for item in items:
            if isinstance(item.value, dict) and item.value.get("step_id") == step_id:
                return Step(**item.value)
        raise HTTPException(status_code=404, detail="no such step")

    @router.get("/tasks/{task_id}/artifacts", response_model=list[Artifact])
    async def list_artifacts(
        task_id: str,
        request: Request,
        caller: str = Depends(caller_dep),
    ) -> list[Artifact]:
        await owned_validator(request, task_id, caller, create=False)
        state = request.app.state.api
        return task_artifacts(state.runtime, task_id)

    @router.get("/tasks/{task_id}/artifacts/{artifact_id}")
    async def download_artifact(
        task_id: str,
        artifact_id: str,
        request: Request,
        caller: str = Depends(caller_dep),
    ) -> FileResponse:
        await owned_validator(request, task_id, caller, create=False)
        state = request.app.state.api
        folder = (state.runtime.out_dir / task_id).resolve()
        if not folder.is_dir():
            raise HTTPException(status_code=404, detail="no artifacts found for this task")

        target_file: Path | None = None
        for p in folder.iterdir():
            if p.is_file() and not p.name.startswith("."):
                if p.name == artifact_id or _file_hash_id(p.name) == artifact_id:
                    target_file = p.resolve()
                    break

        if target_file is None or target_file.parent != folder or not target_file.is_file():
            raise HTTPException(status_code=404, detail="artifact not found")

        media_type, _ = mimetypes.guess_type(target_file.name)
        return FileResponse(
            path=target_file,
            filename=target_file.name,
            media_type=media_type or "application/octet-stream",
        )

    @router.post("/tasks/{task_id}/artifacts", response_model=Artifact)
    async def upload_artifact(
        task_id: str,
        request: Request,
        file: UploadFile = File(...),  # noqa: B008
        caller: str = Depends(caller_dep),
    ) -> Artifact:
        await owned_validator(request, task_id, caller, create=False)
        content = await file.read(MAX_ATTACHMENT_BYTES + 1)
        if len(content) > MAX_ATTACHMENT_BYTES:
            raise HTTPException(status_code=413, detail="file exceeds 200 MiB limit")
        file_name = Path(file.filename or "artifact").name
        if not THREAD_ID.fullmatch(file_name):
            raise HTTPException(
                status_code=400, detail="file names must be letters, digits, dot, dash, underscore"
            )

        state = request.app.state.api
        await state.runtime.attach(task_id, [(file_name, content)])
        return Artifact(
            artifact_id=_file_hash_id(file_name),
            file_name=file_name,
            relative_path=f"attachments/{file_name}",
            created_at=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        )

    return router
